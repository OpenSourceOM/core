package connect

import (
	"regexp"
	"strings"

	"github.com/OpenSourceOM/core/internal/graph"
)

var (
	roleARNPattern    = regexp.MustCompile(`^arn:aws[a-z0-9-]*:iam::[0-9]{12}:role/[A-Za-z0-9+=,./@_-]+$`)
	accountIDPattern  = regexp.MustCompile(`^[0-9]{12}$`)
	uuidPattern       = regexp.MustCompile(`^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$`)
	projectIDPattern  = regexp.MustCompile(`^[a-z][a-z0-9-]{4,28}[a-z0-9]$`)
	memberPattern     = regexp.MustCompile(`^(user|group|serviceAccount):[A-Za-z0-9._%+@-]+$`)
	serviceAccountPat = regexp.MustCompile(`^[a-z][a-z0-9-]{4,28}[a-z0-9]@[a-z][a-z0-9-]{4,28}[a-z0-9]\.iam\.gserviceaccount\.com$`)
	regionPattern     = regexp.MustCompile(`^[a-z0-9-]{1,32}$`)
	locationPattern   = regexp.MustCompile(`^[a-z0-9]{1,32}$`)
	resourceGroupPat  = regexp.MustCompile(`^[A-Za-z0-9._()-]{1,90}$`)
	externalIDPattern = regexp.MustCompile(`^[0-9a-f]{32}$`)
)

func normalize(conn *graph.CloudConnection) {
	conn.Provider = strings.ToLower(strings.TrimSpace(conn.Provider))
	conn.AccountID = strings.TrimSpace(conn.AccountID)
	conn.Region = strings.TrimSpace(conn.Region)
	conn.Location = strings.TrimSpace(conn.Location)
	conn.InventoryRoleARN = strings.TrimSpace(conn.InventoryRoleARN)
	conn.InventoryPrincipal = strings.TrimSpace(conn.InventoryPrincipal)
	conn.ExternalID = strings.TrimSpace(conn.ExternalID)
	conn.ScannerPrincipal = strings.TrimSpace(conn.ScannerPrincipal)
	conn.ScannerAccountID = strings.TrimSpace(conn.ScannerAccountID)
	conn.ResourceGroup = strings.TrimSpace(conn.ResourceGroup)
	conn.SnapshotRoleARN = strings.TrimSpace(conn.SnapshotRoleARN)
	switch conn.Provider {
	case "aws":
		if conn.Region == "" {
			conn.Region = "us-east-1"
		}
	case "azure":
		if conn.Location == "" {
			conn.Location = "eastus"
		}
		if conn.ResourceGroup == "" {
			conn.ResourceGroup = "opensourceom-scanner"
		}
	case "gcp":
		if conn.Region == "" {
			conn.Region = "us-central1"
		}
	}
}

// Validate rejects secrets and values that cannot be dropped into a grant template.
func Validate(conn graph.CloudConnection) error {
	for _, value := range []string{
		conn.AccountID, conn.Region, conn.Location, conn.InventoryRoleARN, conn.InventoryPrincipal,
		conn.ExternalID, conn.ScannerPrincipal, conn.ScannerAccountID, conn.ResourceGroup, conn.SnapshotRoleARN,
	} {
		if looksLikeSecret(value) {
			return &Invalid{Message: "Paste a role ARN, subscription, or project. Do not paste an access key or a client secret."}
		}
	}
	if !externalIDPattern.MatchString(conn.ExternalID) {
		return &Invalid{Message: "The external id is generated by OpenSourceOM. Create the connection again."}
	}
	switch conn.Provider {
	case "aws":
		return validateAWS(conn)
	case "azure":
		return validateAzure(conn)
	case "gcp":
		return validateGCP(conn)
	default:
		return &Invalid{Message: "Choose AWS, Azure, or GCP."}
	}
}

func validateAWS(conn graph.CloudConnection) error {
	if !regionPattern.MatchString(conn.Region) {
		return &Invalid{Message: "Enter a region such as us-east-1."}
	}
	if conn.AccountID != "" && !accountIDPattern.MatchString(conn.AccountID) {
		return &Invalid{Message: "An AWS account id is 12 digits."}
	}
	if conn.ScannerAccountID != "" && !accountIDPattern.MatchString(conn.ScannerAccountID) {
		return &Invalid{Message: "The scanner account id is 12 digits."}
	}
	for _, arn := range []string{conn.InventoryRoleARN, conn.InventoryPrincipal, conn.ScannerPrincipal, conn.SnapshotRoleARN} {
		if arn != "" && !roleARNPattern.MatchString(arn) {
			return &Invalid{Message: "Enter an IAM role ARN, such as arn:aws:iam::123456789012:role/opensourceom-inventory."}
		}
	}
	return nil
}

func validateAzure(conn graph.CloudConnection) error {
	if !locationPattern.MatchString(conn.Location) {
		return &Invalid{Message: "Enter a location such as eastus."}
	}
	if !resourceGroupPat.MatchString(conn.ResourceGroup) {
		return &Invalid{Message: "Enter the scanner resource group name."}
	}
	if conn.AccountID != "" && !uuidPattern.MatchString(conn.AccountID) {
		return &Invalid{Message: "An Azure subscription id is a UUID."}
	}
	if conn.ScannerAccountID != "" && !uuidPattern.MatchString(conn.ScannerAccountID) {
		return &Invalid{Message: "The scanner subscription id is a UUID."}
	}
	for _, id := range []string{conn.InventoryPrincipal, conn.ScannerPrincipal} {
		if id != "" && !uuidPattern.MatchString(id) {
			return &Invalid{Message: "An Azure principal id is the object id, not a client secret."}
		}
	}
	return nil
}

func validateGCP(conn graph.CloudConnection) error {
	if !regionPattern.MatchString(conn.Region) {
		return &Invalid{Message: "Enter a region such as us-central1."}
	}
	if conn.AccountID != "" && !projectIDPattern.MatchString(conn.AccountID) {
		return &Invalid{Message: "Enter a GCP project id."}
	}
	if conn.ScannerAccountID != "" && !projectIDPattern.MatchString(conn.ScannerAccountID) {
		return &Invalid{Message: "Enter the scanner GCP project id."}
	}
	if conn.InventoryPrincipal != "" && !memberPattern.MatchString(conn.InventoryPrincipal) {
		return &Invalid{Message: "The GCP member looks like user:you@example.com or serviceAccount:name@project.iam.gserviceaccount.com."}
	}
	if conn.ScannerPrincipal != "" && !serviceAccountPat.MatchString(conn.ScannerPrincipal) {
		return &Invalid{Message: "The scanner service account looks like opensourceom-worker@project.iam.gserviceaccount.com."}
	}
	return nil
}

func looksLikeSecret(value string) bool {
	lower := strings.ToLower(value)
	switch {
	case strings.Contains(lower, "akia"),
		strings.Contains(lower, "asia"),
		strings.Contains(lower, "begin private"),
		strings.Contains(lower, "client_secret"),
		strings.Contains(lower, "aws_secret"),
		strings.Contains(value, "\n"),
		strings.Contains(value, "'"):
		return true
	default:
		return false
	}
}
